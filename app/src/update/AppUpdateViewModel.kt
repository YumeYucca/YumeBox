package com.github.yumeyucca.yumebox.update

import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.github.yumeyucca.yumebox.BuildInfo
import com.github.yumeyucca.yumebox.data.store.AppSettingsStore
import com.github.yumeyucca.yumebox.data.update.AppUpdateManifest
import com.github.yumeyucca.yumebox.data.update.AppUpdateRepository
import kotlinx.coroutines.Job
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.collectLatest
import kotlinx.coroutines.launch

data class AppUpdateInfo(
    val versionName: String,
    val versionCode: Int,
    val notes: String,
    val downloadUrl: String,
)

/**
 * Checks the channel manifest generated by the release pipeline. Local builds have no
 * base URL/channel and therefore stay silent.
 */
class AppUpdateViewModel(
    private val repository: AppUpdateRepository,
    private val settings: AppSettingsStore,
) : ViewModel() {
    private val baseUrl = BuildInfo.UPDATE_BASE_URL.trim().trimEnd('/')
    private val channel = BuildInfo.UPDATE_CHANNEL.trim()
    private val autoCheckUpdate = settings.autoCheckUpdate
    private var dismissedVersionCode: Int = 0
    private var refreshJob: Job? = null

    private val _update = MutableStateFlow<AppUpdateInfo?>(null)
    val update = _update.asStateFlow()

    init {
        viewModelScope.launch {
            autoCheckUpdate.state.collectLatest { enabled ->
                if (enabled) {
                    refresh()
                } else {
                    refreshJob?.cancel()
                    _update.value = null
                }
            }
        }
    }

    fun refresh() {
        if (!autoCheckUpdate.value) return
        if (baseUrl.isBlank() || channel.isBlank()) return
        refreshJob?.cancel()
        refreshJob = viewModelScope.launch {
            val info =
                repository
                    .fetchLatest(baseUrl, channel)
                    ?.takeIf { it.versionCode > BuildInfo.VERSION_CODE }
                    ?.toInfo()
                    ?.takeIf { it.versionCode != dismissedVersionCode }
            _update.value = info
        }
    }

    /** Called after the user starts the update; keeps the icon hidden for this process. */
    fun dismissForSession() {
        dismissedVersionCode = _update.value?.versionCode ?: return
        _update.value = null
    }
}

private fun AppUpdateManifest.toInfo(): AppUpdateInfo? {
    val packageInfo =
        packages.firstOrNull { !it.geoBundled && it.abi == "arm64-v8a" } ?: return null
    val downloadUrl = packageInfo.downloadUrl.trim()
    if (!downloadUrl.startsWith("https://")) return null
    return AppUpdateInfo(
        versionName = versionName.ifBlank { "v$versionCode" },
        versionCode = versionCode,
        notes = notes,
        downloadUrl = downloadUrl,
    )
}
