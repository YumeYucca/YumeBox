package com.github.yumeyucca.yumebox.update

import android.app.Application
import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.github.yumeyucca.yumebox.BuildInfo
import com.github.yumeyucca.yumebox.core.locale.YumeTxt
import com.github.yumeyucca.yumebox.data.store.AppSettingsStore
import com.github.yumeyucca.yumebox.data.update.AppUpdateManifest
import com.github.yumeyucca.yumebox.data.update.AppUpdateRepository
import kotlinx.coroutines.Job
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.combine
import kotlinx.coroutines.flow.collectLatest
import kotlinx.coroutines.launch

data class AppUpdateInfo(
    val versionName: String,
    val versionCode: Int,
    val notes: String,
    val downloadUrl: String,
    val fileName: String,
    val sizeBytes: Long,
)

/** Progress of the in-dialog update download; `percent` is null until the total is known. */
sealed interface AppUpdateDownloadState {
    data object Idle : AppUpdateDownloadState

    data class Downloading(val percent: Int?) : AppUpdateDownloadState
}

/**
 * Checks the channel manifest generated by the release pipeline. Local builds have no
 * base URL/channel and therefore stay silent.
 */
class AppUpdateViewModel(
    private val application: Application,
    private val repository: AppUpdateRepository,
    private val settings: AppSettingsStore,
) : ViewModel() {
    private val baseUrl = BuildInfo.UPDATE_BASE_URL.trim().trimEnd('/')
    private val autoCheckUpdate = settings.autoCheckUpdate
    private var dismissedVersionCode: Int = 0
    private var refreshJob: Job? = null

    private val _update = MutableStateFlow<AppUpdateInfo?>(null)
    val update = _update.asStateFlow()

    private val _downloadState = MutableStateFlow<AppUpdateDownloadState>(AppUpdateDownloadState.Idle)
    val downloadState = _downloadState.asStateFlow()

    private val _downloadError = MutableStateFlow<String?>(null)
    val downloadError = _downloadError.asStateFlow()

    private var downloadJob: Job? = null

    init {
        viewModelScope.launch {
            combine(
                autoCheckUpdate.state,
                settings.updateChannel.state,
            ) { enabled, _ -> enabled }
                .collectLatest { enabled ->
                    if (enabled) {
                        refresh()
                    } else {
                        refreshJob?.cancel()
                        _update.value = null
                    }
                }
        }
    }

    fun refresh() {
        if (!autoCheckUpdate.value) return
        if (baseUrl.isBlank()) return
        val channel =
            AppUpdateChannel.resolve(settings.updateChannel.value, BuildInfo.UPDATE_CHANNEL).key
        refreshJob?.cancel()
        refreshJob = viewModelScope.launch {
            val info =
                repository
                    .fetchLatest(baseUrl, channel)
                    ?.takeIf { it.versionCode > BuildInfo.VERSION_CODE }
                    ?.toInfo()
                    ?.takeIf { it.versionCode != dismissedVersionCode }
            _update.value = info
        }
    }

    /** Called after the user starts the update; keeps the icon hidden for this process. */
    fun dismissForSession() {
        dismissedVersionCode = _update.value?.versionCode ?: return
        _update.value = null
    }

    /** Downloads the current update into the public Download folder and starts the installer. */
    fun startDownload() {
        val info = _update.value ?: return
        if (downloadJob?.isActive == true) return
        _downloadState.value = AppUpdateDownloadState.Downloading(null)
        downloadJob = viewModelScope.launch {
            var lastPercent: Int? = null
            val installed =
                AppUpdateInstaller.downloadAndInstall(application, repository, info) { progress ->
                    val percent = progress?.let { (it * 100).toInt() }
                    if (percent != lastPercent) {
                        lastPercent = percent
                        // Whole-percent steps keep the dialog from recomposing on every chunk.
                        _downloadState.value = AppUpdateDownloadState.Downloading(percent)
                    }
                }
            if (installed) {
                dismissForSession()
            } else {
                _downloadError.value = YumeTxt.Home.Update.DownloadFailed
            }
            _downloadState.value = AppUpdateDownloadState.Idle
        }
    }

    fun cancelDownload() {
        downloadJob?.cancel()
        downloadJob = null
        _downloadState.value = AppUpdateDownloadState.Idle
    }

    fun consumeDownloadError() {
        _downloadError.value = null
    }
}

private fun AppUpdateManifest.toInfo(): AppUpdateInfo? {
    val packageInfo =
        packages.firstOrNull { !it.geoBundled && it.abi == "arm64-v8a" } ?: return null
    val downloadUrl = packageInfo.downloadUrl.trim()
    if (!downloadUrl.startsWith("https://")) return null
    val versionName = versionName.ifBlank { "v$versionCode" }
    return AppUpdateInfo(
        versionName = versionName,
        versionCode = versionCode,
        notes = notes,
        downloadUrl = downloadUrl,
        fileName = packageInfo.fileName.ifBlank { "YumeBox-$versionName.apk" },
        sizeBytes = packageInfo.size,
    )
}
